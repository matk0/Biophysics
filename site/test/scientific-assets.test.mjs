import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, rm, symlink, truncate, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";

test("scientific publication rejects changed sources, missing outputs, and escaped manifest paths", async (t) => {
  const { verifyGeneratedAssets } = await import("../src/lib/scientific-assets.mjs");
  const root = await mkdtemp(path.join(os.tmpdir(), "biophysics-scientific-assets-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const base = "Assets/concepts/hydrogen";
  await mkdir(path.join(root, base), { recursive: true });
  const source = `${base}/model.v1.json`;
  const output = `${base}/scene.usda`;
  await writeFile(path.join(root, source), '{"model":"hydrogen"}');
  await writeFile(path.join(root, output), "#usda 1.0\n");
  const record = async (name) => ({ path: name, sha256: createHash("sha256").update(await readFile(path.join(root, name))).digest("hex") });
  const manifest = { schema: "hydrogen-generated/v1", sources: [await record(source)], outputs: [await record(output)] };
  const manifestPath = `${base}/generated.v1.json`;
  const save = () => writeFile(path.join(root, manifestPath), JSON.stringify(manifest));
  const verify = () => verifyGeneratedAssets({ vaultRoot: root, concept: "hydrogen", manifestPath });
  await save();
  assert.equal((await verify()).outputs.length, 1);
  await truncate(path.join(root, output), 25 * 1024 * 1024 + 1);
  await assert.rejects(verify(), /oversized/i);
  await writeFile(path.join(root, output), "#usda 1.0\n");
  await writeFile(path.join(root, source), '{"model":"changed"}');
  await assert.rejects(verify(), /stale.*model\.v1\.json/i);
  await writeFile(path.join(root, source), '{"model":"hydrogen"}');
  await writeFile(path.join(root, output), "#usda 1.0\nchanged");
  await assert.rejects(verify(), /stale.*scene\.usda/i);
  await rm(path.join(root, output));
  await assert.rejects(verify(), /missing.*scene\.usda/i);
  await writeFile(path.join(root, output), "#usda 1.0\n");
  manifest.outputs[0].path = `${base}/../../private.usda`;
  await save();
  await assert.rejects(verify(), /contained.*path/i);
  manifest.outputs[0].path = `${base}/outside.usda`;
  await symlink(path.join(root, "outside.usda"), path.join(root, manifest.outputs[0].path));
  await writeFile(path.join(root, "outside.usda"), "#usda 1.0\n");
  await save();
  await assert.rejects(verify(), /outside.*concept assets/i);
});
